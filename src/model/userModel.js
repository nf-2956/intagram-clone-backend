const mongoose = require("mongoose")

const userModel = new mongoose.Schema({
    username: {
        type: String,
        required: true,
        unique: true
    },
    email: {
        type: String,
        required: true,
        unique: true
    },
    password: {
        type: String,
        required: true
    },
    avatar: {
        type: String,
        default : ""
    },
})

module.exports = mongoose.model("InstaUser", userModel)